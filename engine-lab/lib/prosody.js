/* Prosody layer: item strings -> syllable readings, every decision tagged with a rule id
   from rules.json. Nothing here knows about meters; lib/meter.js does the matching.

   A READING is { syl:[Syl], dec:[{id,opt,key}], cost } where each Syl is
     { w:'l'|'s'|'x', text, flex:{id,key,word}|null, cheat:bool, n:letters, iz, conj }
   'x' = flexible (1.5); its P(short) comes from params via flex.id/key/word.
   dec lists the choice rules applied (including the default option), so the learner
   can count opportunities as well as firings. */
