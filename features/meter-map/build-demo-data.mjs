#!/usr/bin/env node
/**
 * build-demo-data.mjs
 * -----------------------------------------------------------------------
 * Tiny, dependency-free build step for demo.html. Reads the app's real
 * ../../data/meters.json, flattens its three sections (standard, rubai,
 * hindi_info) into one array shaped for meterMap.js, and writes
 * demo-data.js — a plain <script> (not a module) that sets
 * window.METER_MAP_DEMO_DATA. demo.html then loads that file directly,
 * so the demo works fully offline over file:// with no fetch() call
 * (which local Chrome/Firefox block for file:// JSON under CORS rules).
 *
 * Run with:  node build-demo-data.mjs
 * Re-run any time data/meters.json changes upstream.
 * -----------------------------------------------------------------------
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const sourcePath = join(here, '..', '..', 'data', 'meters.json');
const outPath = join(here, 'demo-data.js');

const raw = JSON.parse(readFileSync(sourcePath, 'utf8'));

const standard = raw.standard.map((m) => ({ ...m, group: 'standard' }));

const rubai = raw.rubai.map((m) => ({ ...m, group: 'rubai' }));

const hindi = [{
  id: 'HINDI',
  name: "Mir's Hindi meter",
  group: 'hindi',
  description: raw.hindi_info.description,
  feet: raw.hindi_info.feet,
  paired: [],
}];

const meters = [...standard, ...rubai, ...hindi];

const pairs = [];
const seen = new Set();
for (const m of standard) {
  for (const otherId of m.paired || []) {
    const key = m.id < otherId ? `${m.id}|${otherId}` : `${otherId}|${m.id}`;
    if (seen.has(key)) continue;
    seen.add(key);
    pairs.push([m.id, otherId]);
  }
}

const banner = '// AUTO-GENERATED by build-demo-data.mjs from ../../data/meters.json. Do not edit by hand.\n';
const contents = `${banner}window.METER_MAP_DEMO_DATA = ${JSON.stringify({ meters, pairs }, null, 2)};\n`;

writeFileSync(outPath, contents, 'utf8');
console.log(`Wrote ${outPath} (${meters.length} meters, ${pairs.length} pairs)`);
